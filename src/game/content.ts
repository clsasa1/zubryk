export function shuffle<T>(list: T[]): T[] {
  const copy = list.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const cur = copy[i];
    const swap = copy[j];
    if (cur === undefined || swap === undefined) continue;
    copy[i] = swap;
    copy[j] = cur;
  }
  return copy;
}
